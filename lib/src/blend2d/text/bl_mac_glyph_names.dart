/// Os 258 nomes de glifo padrão do Macintosh, usados pela tabela `post`.
///
/// A tabela `post` versão 1.0 declara que a fonte usa exatamente esta ordem;
/// a versão 2.0 traz um índice por glifo em que valores abaixo de 258 apontam
/// para esta tabela e valores a partir de 258 apontam para a lista de nomes
/// Pascal que vem logo depois do índice.
///
/// Fonte: Apple 'TrueType Reference Manual', capítulo sobre a tabela `post`
/// (Macintosh ordering), reproduzida em OpenType 1.9 §`post`.
library;

/// Nome padrão do glifo de índice [index], ou `null` fora da faixa 0..257.
String? macStandardGlyphName(int index) {
  if (index < 0 || index >= macStandardGlyphNames.length) return null;
  return macStandardGlyphNames[index];
}

